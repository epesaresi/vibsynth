"""Benchmark of the kurtosis of the oscillator responses (k_z) on the two synthetic
records with frequency-dependent non-Gaussianity.

    python tools/kz_benchmark.py [--seeds 1,2,3] [--duration 60] [--out kz_benchmark.json]

The records are generated by examples/make_multisource.py (road, engine and
impact sources) and examples/make_sor.py (engine lines in some blocks only).
Damage model: 5-300 Hz, 1/12 octave, Q = 10, b = 8; the 300 s records are
synthesised into 60 s tests (life compressed 5 times). Every row reports, as
the mean over the seeds, the maximum and median FDS error and the median
absolute error of k_z(fn), the kurtosis of the oscillator responses.
"""
import argparse
import json
import os
import sys
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
sys.path.insert(0, os.path.join(HERE, "..", "examples"))
import vibsynth as vs  # noqa: E402
from vibsynth.pipeline import run_method  # noqa: E402
import make_multisource  # noqa: E402
import make_sor  # noqa: E402

CASES = {
    "multisource": (make_multisource.make, ("gaussian", "kfds", "mmvsd", "mmvsd pattern")),
    "sine-on-random": (lambda: make_sor.make()[:2], ("gaussian", "kfds", "sor", "mmvsd")),
}


def run(seeds, duration):
    out = []
    for case, (make, methods) in CASES.items():
        x, fs = make()
        ref = vs.analyze_reference(x, fs, fmin=5, fmax=300, Q=10, b=8)
        kref = ref.response_kurtosis
        print(f"==== {case}: {x.size / fs:.0f} s, kurtosis {ref.stats['kurtosis']:.2f}, "
              f"k_z {kref.min():.1f} to {kref.max():.1f}")
        for m in methods:
            rows = []
            for sd in seeds:
                t0 = time.time()
                kw = {"modulation": "pattern", "mapping": "compress"} if m == "mmvsd pattern" else {}
                r = run_method(ref, m.split()[0], duration, seed=sd, iterations=40,
                               tol=0.10 if m.startswith("mmvsd") else 0.05, **kw)
                ev = vs.evaluate(r.x, r.fs, ref, repeats=r.repeats, fds=r.info["fds_measured"],
                                 mrs=r.info["mrs_measured"], k_response=r.info.get("k_response"))
                rows.append((ev["fds_max_error_pct"], ev["fds_median_error_pct"], ev["kz_median_abs_err"],
                             ev["stats"]["kurtosis"], float(np.max(ev["mrs_ratio"])), time.time() - t0))
            a = np.array(rows)
            row = dict(case=case, method=m, seeds=list(seeds), fds_max=round(float(a[:, 0].mean()), 1),
                       fds_max_each=[round(float(v), 1) for v in a[:, 0]],
                       fds_median=round(float(a[:, 1].mean()), 1), kz_median=round(float(a[:, 2].mean()), 2),
                       kurtosis=round(float(a[:, 3].mean()), 2), mrs_max_ratio=round(float(a[:, 4].mean()), 2),
                       seconds=round(float(a[:, 5].mean()), 1))
            out.append(row)
            print(row, flush=True)
    return dict(settings=dict(fmin=5, fmax=300, Q=10, b=8, duration=duration), rows=out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seeds", default="1,2,3")
    ap.add_argument("--duration", type=float, default=60.0)
    ap.add_argument("--out", default="kz_benchmark.json")
    a = ap.parse_args()
    res = run([int(s) for s in a.seeds.split(",")], a.duration)
    with open(a.out, "w") as f:
        json.dump(res, f, indent=1)
    print("written", a.out)
